// Exercício 7: Calcule a área de um triângulo.

alert ("Área de triângulo");

let baseTriangulo = parseFloat(prompt("Informe o valor da base do triângulo em centimetros: "));

let alturaTriangulo = parseFloat(prompt("Informe a altura do Triângulo em centímetros: "));

let areaTriangulo = (baseTriangulo * alturaTriangulo) / 2;

alert("A Área total do Triângulo de largura" + baseTriangulo + "cm e altura" + alturaTriangulo + "cm é:" + areaTriangulo + "cm²");
