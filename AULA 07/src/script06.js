// Exercício 6: Calcule a área de um quadrado.

alert ("Área do Quadrado");

let larguraQuadrado = parseFloat(prompt("Informe o valor da largura do quadrado em centimetros: "));

let alturaQuadrado = parseFloat(prompt("Informe a altura do quadrado em centímetros: "));

let areaQuadrado = larguraQuadrado * alturaQuadrado;

alert("A Área total do Quadrado de largura" + larguraQuadrado + "cm e altura" + alturaQuadrado + "cm é:" + areaQuadrado + "cm²");
