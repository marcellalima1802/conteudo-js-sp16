// Exercício 2: Subtraindo valores informados pelo usuário.

alert("Subtraindo valores informados");

let valor1 = parseFloat(prompt("Informe o primeiro valor: "));

let valor2 = parseFloat(prompt("Informe o segundo valor: "));

let resultadoSubtração = valor1 - valor2;

alert("O resultado da subtração dos valores informados é: " + resultadoSubtração);