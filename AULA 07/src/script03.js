// Exercício 3: Multiplicando valores informados pelo usuário.

alert("Multiplicando valores");

let valor1 = parseFloat(prompt("Informe o primeiro valor: "));

let valor2 = parseFloat(prompt("Informe o segundo valor: "));

let resultadoMultiplicação = valor1 * valor2;

alert("O resultado da multiplicação dos valores informados é: " + resultadoMultiplicação);